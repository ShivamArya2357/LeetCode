package Practice.src.javapractice;

public class Student2 {

    private int rollNo;

    private String studentName;

    private int marks;

    public Student2(int rollNo, String studentName, int marks) {
        this.rollNo = rollNo;
        this.studentName = studentName;
        this.marks = marks;
    }

    public int getRollNo() {
        return rollNo;
    }

    public String getStudentName() {
        return studentName;
    }

    public int getMarks() {
        return marks;
    }
}
